"""Pack the demo's runtime files into web_sim/files.js.

Usage: python web_sim/pack_files.py

Reads the repository-relative paths listed in web_sim/files.json and writes
web_sim/files.js, which index.html loads with a plain <script> tag. Embedding
the files (instead of fetch()ing them) is what lets the page run when opened
from disk, where browsers block fetch(). Re-run after changing files.json or
after the listed files change.
"""

import base64
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))


def main():
    with open(os.path.join(HERE, "files.json"), encoding="utf-8") as f:
        paths = json.load(f)

    entries = []
    total = 0
    for path in paths:
        full = os.path.join(ROOT, path)
        if not os.path.isfile(full):
            print("missing file listed in files.json: %s" % path)
            return 1
        with open(full, "rb") as f:
            data = f.read()
        total += len(data)
        entries.append("  %s: \"%s\"," % (json.dumps(path), base64.b64encode(data).decode("ascii")))

    out = os.path.join(HERE, "files.js")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by web_sim/pack_files.py. Do not edit. */\n")
        f.write("globalThis.HONEYGUI_WEB_SIM_FILES = {\n")
        f.write("\n".join(entries))
        f.write("\n};\n")
    print("packed %d file(s), %d bytes -> %s" % (len(paths), total, out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
