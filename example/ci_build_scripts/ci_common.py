# ---------------------------------------------------------------- platform ---

IS_WINDOWS = sys.platform == "win32"
CMAKE_GENERATOR = "MinGW Makefiles" if IS_WINDOWS else "Unix Makefiles"
SCONS_COMMAND = "scons.exe" if IS_WINDOWS else "scons"

# Builds always go through "cmake --build", which drives whichever tool the
# generator needs (mingw32-make / make). Nothing here should invoke make itself.


def fix_console_encoding():
    """Force UTF-8 on the Windows console so build output does not crash us."""
    if IS_WINDOWS:
        for name in ("stdout", "stderr"):
            stream = getattr(sys, name)
            if hasattr(stream, "reconfigure"):
                stream.reconfigure(encoding="utf-8", errors="replace")
            elif hasattr(stream, "buffer"):
                setattr(sys, name, codecs.getwriter("utf-8")(
                    stream.buffer, "replace"))


